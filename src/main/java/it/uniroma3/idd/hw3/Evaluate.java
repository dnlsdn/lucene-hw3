    // ------------------------------------------------------------------ 4. name analyzers

    List<NameQuery> nameQueries() {
        List<NameQuery> list = new ArrayList<>();
        // 20 Newsgroups: the group is part of the file name, so the answer is known
        for (String[] q : new String[][] {
                {"graphics", "comp.graphics"}, {"space", "sci.space"}, {"hockey", "rec.sport.hockey"},
                {"crypt", "sci.crypt"}, {"autos", "rec.autos"}, {"med", "sci.med"},
                {"religion", "soc.religion.christian talk.religion.misc"},
                {"politics", "talk.politics.guns talk.politics.mideast talk.politics.misc"},
                {"hardware", "comp.sys.ibm.pc.hardware comp.sys.mac.hardware"},
                {"windows", "comp.os.ms-windows.misc comp.windows.x"},
                {"sport", "rec.sport.baseball rec.sport.hockey"},
                {"sci.space", "sci.space"}, {"comp.sys.mac.hardware", "comp.sys.mac.hardware"}}) {
            Set<String> groups = Set.of(q[1].split(" "));
            list.add(new NameQuery(q[0], "posts of " + q[1].replace(" ", ", "), name -> {
                var m = NEWS.matcher(name);
                return m.matches() && groups.contains(m.group(1));
            }));
        }
        // Cranfield: relevant = documents whose full title contains the word
        for (String word : List.of("slipstream", "hypersonic", "buckling", "flutter", "cylinder",
                "turbulent", "vortex", "heat")) {
            Pattern w = Pattern.compile("\\b" + word + "\\b");
            list.add(new NameQuery(word, "Cranfield titles containing \"" + word + "\"", name -> {
                var m = CRAN.matcher(name);
                return m.matches() && w.matcher(titles.getOrDefault(Integer.parseInt(m.group(1)), "")).find();
            }));
        }
        return list;
    }

    void nameAnalyzers() throws Exception {
        List<Path> all = IndexBuilder.listTxtFiles(docs);
        List<NameQuery> nq = nameQueries();
        md.append("## 4. Name analyzers (queries \"nome ...\" with known answers)\n\n")
                .append("Unranked evaluation: every matching document is retrieved. Macro averages over ")
                .append(nq.size()).append(" queries.\n\n")
                .append("| analyzer | precision | recall | F1 | queries with no result |\n|---|---|---|---|---|\n");
        try (PrintWriter csv = csv("name_analyzers.csv")) {
            csv.println("analyzer,query,relevant,retrieved,precision,recall,f1");
            for (String name : Analyzers.NAME_CHOICES) {
                Analyzer analyzer = Analyzers.perField(name, Analyzers.DEFAULT_CONTENT);
                QueryFactory factory = new QueryFactory(analyzer);
                Path tmp = Files.createTempDirectory("hw3-idx");
                try (Directory dir = FSDirectory.open(tmp)) {
                    IndexBuilder.build(all, dir, analyzer, null);
                    try (DirectoryReader reader = DirectoryReader.open(dir)) {
                        IndexSearcher searcher = new IndexSearcher(reader);
                        String[] names = storedNames(reader);
                        double[] p = new double[nq.size()], r = new double[nq.size()], f = new double[nq.size()];
                        int empty = 0;
                        for (int i = 0; i < nq.size(); i++) {
                            NameQuery q = nq.get(i);
                            Set<Integer> relevant = new HashSet<>();
                            for (int d = 0; d < names.length; d++) if (q.isRelevant().test(names[d])) relevant.add(d);
                            Set<Integer> retrieved = new HashSet<>();
                            for (ScoreDoc sd : searcher.search(factory.parse("nome " + q.text()), reader.maxDoc()).scoreDocs) {
                                retrieved.add(sd.doc);
                            }
                            if (retrieved.isEmpty()) empty++;
                            Metrics.SetScores s = Metrics.setScores(retrieved, relevant);
                            p[i] = s.precision(); r[i] = s.recall(); f[i] = s.f1();
                            csv.printf(Locale.ROOT, "%s,%s,%d,%d,%.4f,%.4f,%.4f%n", name, q.text(),
                                    relevant.size(), retrieved.size(), p[i], r[i], f[i]);
                        }
                        md.append(String.format(Locale.ROOT, "| %s | %.3f | %.3f | %.3f | %d |%n",
                                name, Metrics.mean(p), Metrics.mean(r), Metrics.mean(f), empty));
                    }
                } finally {
                    deleteRecursively(tmp);
                }
            }
        }
        md.append("\nQueries: ");
        for (int i = 0; i < nq.size(); i++) {
            md.append(i == 0 ? "" : "; ").append('`').append(nq.get(i).text()).append("` (").append(nq.get(i).description()).append(')');
        }
        md.append(".\n\n");
    }

    // ------------------------------------------------------------------ 6. console test queries

    /**
     * A test query typed at the console, with the way its answer is judged:
     * "group" = posts of the given newsgroups, "cran" = Cranfield judgments of query N,
     * "title" = Cranfield titles containing the word (for nome queries).
     */
    record ConsoleQuery(String line, String judge, String arg) {}

    static final List<ConsoleQuery> CONSOLE_QUERIES = List.of(
            new ConsoleQuery("nome graphics", "group", "comp.graphics"),
            new ConsoleQuery("nome comp.sys.mac.hardware", "group", "comp.sys.mac.hardware"),
            new ConsoleQuery("nome politics -guns", "group", "talk.politics.mideast talk.politics.misc"),
            new ConsoleQuery("nome slipstream", "title", "slipstream"),
            new ConsoleQuery("contenuto \"boundary layer\" transition detect", "cran", "39"),
            new ConsoleQuery("contenuto shock-induced \"boundary layer\" separation", "cran", "90"),
            new ConsoleQuery("contenuto +buckling \"cylindrical shells\" imperfections", "cran", "100"),
            new ConsoleQuery("contenuto \"heat transfer\" \"stagnation point\" blunt", "cran", "94"),
            new ConsoleQuery("contenuto \"panel flutter\" \"elastic restraint\"~1", "cran", "111"),
            new ConsoleQuery("contenuto hockey \"stanley cup\"", "group", "rec.sport.hockey"),
            new ConsoleQuery("contenuto encryption +clipper", "group", "sci.crypt"),
            new ConsoleQuery("contenuto \"space shuttle\" -orbit", "group", "sci.space"));

    void consoleQueries() throws Exception {
        List<Path> all = IndexBuilder.listTxtFiles(docs);
        Analyzer analyzer = Analyzers.perField();
        QueryFactory factory = new QueryFactory(analyzer);
        QueryParser bagOfWords = new QueryParser(Analyzers.CONTENT_FIELD, analyzer);
        Map<Integer, String> cranText = new HashMap<>();
        for (CranQuery q : queries) cranText.put(q.id(), q.text());
        Files.write(results.resolve("console-queries.txt"), CONSOLE_QUERIES.stream().map(ConsoleQuery::line).toList());

        md.append("## 6. Console test queries (full index, final configuration)\n\n")
                .append("Every query has a known answer: the newsgroup of the post, the Cranfield judgments of the ")
                .append("query it rephrases, or the full Cranfield title. For Cranfield, AP of the rephrased console ")
                .append("query is compared with AP of the original natural-language query.\n\n")
                .append("| # | console query | Lucene query | hits | relevant | P@10 | recall (all hits) | AP | AP original query |\n")
                .append("|---|---|---|---|---|---|---|---|---|\n");
        Path tmp = Files.createTempDirectory("hw3-idx");
        try (Directory dir = FSDirectory.open(tmp)) {
            IndexBuilder.build(all, dir, analyzer, null);
            try (DirectoryReader reader = DirectoryReader.open(dir)) {
                IndexSearcher searcher = new IndexSearcher(reader);
                String[] names = storedNames(reader);
                int i = 1;
                for (ConsoleQuery cq : CONSOLE_QUERIES) {
                    java.util.function.Predicate<Integer> relevant = relevanceOf(cq, names);
                    Set<Integer> relSet = new HashSet<>();
                    for (int d = 0; d < names.length; d++) if (relevant.test(d)) relSet.add(d);
                    var lq = factory.parse(cq.line());
                    TopDocs top = searcher.search(lq, reader.maxDoc());
                    List<Integer> ranking = new ArrayList<>();
                    for (ScoreDoc sd : top.scoreDocs) ranking.add(sd.doc);
                    String original = "-";
                    if (cq.judge().equals("cran")) {
                        TopDocs o = searcher.search(bagOfWords.parse(QueryParser.escape(cranText.get(Integer.parseInt(cq.arg())))), DEPTH);
                        List<Integer> or = new ArrayList<>();
                        for (ScoreDoc sd : o.scoreDocs) or.add(sd.doc);
                        original = String.format(Locale.ROOT, "%.3f", Metrics.averagePrecision(or, relSet));
                    }
                    String judged = switch (cq.judge()) {
                        case "cran" -> "Cranfield q" + cq.arg();
                        case "title" -> "titles with \"" + cq.arg() + "\"";
                        default -> cq.arg();
                    };
                    md.append(String.format(Locale.ROOT, "| %d | `%s` | `%s` | %,d | %,d (%s) | %.2f | %.3f | %.3f | %s |%n",
                            i++, cq.line(), lq.toString().replace("|", "\\|"), top.totalHits.value(), relSet.size(), judged,
                            Metrics.precisionAt(ranking, relSet, 10), Metrics.recallAt(ranking, relSet, ranking.size()),
                            Metrics.averagePrecision(ranking, relSet), original));
                }
            }
        } finally {
            deleteRecursively(tmp);
        }
        md.append('\n');
    }

    private java.util.function.Predicate<Integer> relevanceOf(ConsoleQuery cq, String[] names) {
        return switch (cq.judge()) {
            case "group" -> {
                Set<String> groups = Set.of(cq.arg().split(" "));
                yield d -> { var m = NEWS.matcher(names[d]); return m.matches() && groups.contains(m.group(1)); };
            }
            case "cran" -> {
                Set<Integer> rel = qrels.get(Integer.parseInt(cq.arg())).keySet();
                yield d -> { var m = CRAN.matcher(names[d]); return m.matches() && rel.contains(Integer.parseInt(m.group(1))); };
            }
            case "title" -> {
                Pattern w = Pattern.compile("\\b" + cq.arg() + "\\b");
                yield d -> { var m = CRAN.matcher(names[d]);
                    return m.matches() && w.matcher(titles.getOrDefault(Integer.parseInt(m.group(1)), "")).find(); };
            }
            default -> throw new IllegalArgumentException(cq.judge());
        };
    }

    // ------------------------------------------------------------------ 5. indexing time

    /** One indexing configuration of the timing experiments. */
    record TimingConfig(String group, String label, List<Path> files, String contentAnalyzer, double ramMB) {}

    void indexingTime() throws Exception {
        List<Path> all = IndexBuilder.listTxtFiles(docs);
        long bytes = 0;
        for (Path p : all) bytes += Files.size(p);

        List<TimingConfig> configs = new ArrayList<>();
        for (String a : List.of(Analyzers.WHITESPACE, Analyzers.STANDARD, Analyzers.ENGLISH)) {
            configs.add(new TimingConfig("analyzer", a, all, a, 16));
        }
        for (int n : new int[] {1000, 2500, 5000, 10000, all.size()}) {
            configs.add(new TimingConfig("scaling", String.valueOf(n), IndexBuilder.sample(all, n, SEED),
                    Analyzers.DEFAULT_CONTENT, 16));
        }
        for (double ram : new double[] {16, 64, 256}) {
            configs.add(new TimingConfig("ram", String.format(Locale.ROOT, "%.0f", ram), all,
                    Analyzers.DEFAULT_CONTENT, ram));
        }

        // Interleaved rounds: in every round each configuration runs once, so slow drifts of
        // the machine (OS cache, memory pressure, CPU frequency) affect all of them equally.
        int rounds = 5;
        Map<TimingConfig, List<IndexBuilder.Stats>> stats = new LinkedHashMap<>();
        for (TimingConfig c : configs) stats.put(c, new ArrayList<>());
        try (PrintWriter csv = csv("timing.csv")) {
            csv.println("group,config,round,files,mb,total_s,read_s,add_s,commit_s,index_mb,segments");
            for (int round = 0; round <= rounds; round++) {           // round 0 = warm-up, discarded
                for (TimingConfig c : configs) {
                    Path tmp = Files.createTempDirectory("hw3-idx");
                    try (Directory dir = FSDirectory.open(tmp)) {
                        IndexBuilder.Stats s = IndexBuilder.build(c.files(), dir,
                                Analyzers.perField(Analyzers.DEFAULT_NAME, c.contentAnalyzer()), null, c.ramMB());
                        if (round == 0) continue;
                        stats.get(c).add(s);
                        csv.printf(Locale.ROOT, "%s,%s,%d,%d,%.2f,%.4f,%.4f,%.4f,%.4f,%.2f,%d%n", c.group(), c.label(),
                                round, s.files(), s.bytes() / 1e6, s.totalSeconds(), s.readNanos() / 1e9,
                                s.addNanos() / 1e9, s.commitNanos() / 1e9, s.indexBytes() / 1e6, s.segments());
                    } finally {
                        deleteRecursively(tmp);
                    }
                }
            }
        }

        md.append("## 5. Indexing time\n\n")
                .append(String.format(Locale.ROOT, "Full corpus: %,d files, %.1f MB. %d interleaved rounds after one warm-up round "
                        + "(every configuration once per round, files already in the OS cache). Times in seconds, mean ± standard deviation over the rounds.%n%n",
                        all.size(), bytes / 1e6, rounds));
        String header = "| %s | total s | read s | addDocument s | commit s | docs/s | MB/s | index MB | segments |\n|---|---|---|---|---|---|---|---|---|\n";
        md.append("### 5.1 Cost of the content analyzer (full corpus, name analyzer = filename)\n\n")
                .append(String.format(header, "content analyzer"));
        stats.forEach((c, s) -> { if (c.group().equals("analyzer")) md.append(timingRow(c.label(), s)); });
        md.append("\n### 5.2 Growth with the number of files (final configuration)\n\n")
                .append("Random samples of the corpus (fixed seed), same files in every round.\n\n")
                .append(String.format(header, "files"));
        stats.forEach((c, s) -> { if (c.group().equals("scaling")) md.append(timingRow(String.format(Locale.ROOT, "%,d", c.files().size()), s)); });
        md.append("\n### 5.3 RAM buffer of the IndexWriter (full corpus, final configuration)\n\n")
                .append("When the buffer is full Lucene flushes a new segment to disk; segments are later merged.\n\n")
                .append(String.format(header, "RAM buffer MB"));
        stats.forEach((c, s) -> { if (c.group().equals("ram")) md.append(timingRow(c.label() + (c.ramMB() == 16 ? " (default)" : ""), s)); });
        md.append('\n');
    }

    private static String timingRow(String label, List<IndexBuilder.Stats> stats) {
        double[] tot = stats.stream().mapToDouble(IndexBuilder.Stats::totalSeconds).toArray();
        double[] read = stats.stream().mapToDouble(s -> s.readNanos() / 1e9).toArray();
        double[] add = stats.stream().mapToDouble(s -> s.addNanos() / 1e9).toArray();
        double[] commit = stats.stream().mapToDouble(s -> s.commitNanos() / 1e9).toArray();
        IndexBuilder.Stats first = stats.get(0);
        return String.format(Locale.ROOT, "| %s | %.2f ± %.2f | %.2f | %.2f | %.2f | %,.0f | %.1f | %.1f | %d |%n", label,
                Metrics.mean(tot), Metrics.std(tot), Metrics.mean(read), Metrics.mean(add), Metrics.mean(commit),
                first.files() / Metrics.mean(tot), first.bytes() / 1e6 / Metrics.mean(tot), first.indexBytes() / 1e6,
                first.segments());
    }

    // ------------------------------------------------------------------ ranked evaluation

    Run rankedRun(String label, IndexSearcher searcher, Analyzer analyzer) throws Exception {
        String[] names = storedNames(searcher.getIndexReader());
        int[] cranId = new int[names.length];
        for (int d = 0; d < names.length; d++) {
            var m = CRAN.matcher(names[d]);
            cranId[d] = m.matches() ? Integer.parseInt(m.group(1)) : -1 - d; // negative: never relevant
        }
        // bag of words: the query text is escaped, terms are OR-ed and ranked by the similarity
        QueryParser parser = new QueryParser(Analyzers.CONTENT_FIELD, analyzer);
        int n = queries.size();
        double[] ap = new double[n], p10 = new double[n], r100 = new double[n], r1000 = new double[n],
                rprec = new double[n], rr = new double[n], ndcg = new double[n], curve = new double[11];
        double newsInTop10 = 0;
        for (int i = 0; i < n; i++) {
            CranQuery q = queries.get(i);
            TopDocs top = searcher.search(parser.parse(QueryParser.escape(q.text())), DEPTH);
            List<Integer> ranking = new ArrayList<>();
            for (ScoreDoc sd : top.scoreDocs) ranking.add(cranId[sd.doc]);
            for (int k = 0; k < Math.min(10, ranking.size()); k++) if (ranking.get(k) < 0) newsInTop10++;
            Map<Integer, Integer> grades = qrels.get(q.id());
            Set<Integer> relevant = grades.keySet();
            ap[i] = Metrics.averagePrecision(ranking, relevant);
            p10[i] = Metrics.precisionAt(ranking, relevant, 10);
            r100[i] = Metrics.recallAt(ranking, relevant, 100);
            r1000[i] = Metrics.recallAt(ranking, relevant, 1000);
            rprec[i] = Metrics.rPrecision(ranking, relevant);
            rr[i] = Metrics.reciprocalRank(ranking, relevant);
            ndcg[i] = Metrics.ndcgAt(ranking, grades, 10);
            double[] pts = Metrics.elevenPoint(ranking, relevant);
            for (int l = 0; l < 11; l++) curve[l] += pts[l] / n;
        }
        return new Run(label, ap, p10, r100, r1000, rprec, rr, ndcg, curve, newsInTop10 / n);
    }

    private static String row(Run r) {
        return String.format(Locale.ROOT, "| %s | %.4f | %.4f | %.4f | %.4f | %.4f | %.4f | %.4f |", r.label(),
                Metrics.mean(r.ap()), Metrics.mean(r.p10()), Metrics.mean(r.r100()), Metrics.mean(r.r1000()),
                Metrics.mean(r.rprec()), Metrics.mean(r.rr()), Metrics.mean(r.ndcg10()));
    }

    private static String fmtP(double p) {
        return p < 0.001 ? "< 0.001" : String.format(Locale.ROOT, "%.3f", p);
    }

