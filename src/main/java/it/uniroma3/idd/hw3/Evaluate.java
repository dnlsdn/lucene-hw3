    private static String[] storedNames(org.apache.lucene.index.IndexReader reader) throws IOException {
        StoredFields stored = reader.storedFields();
        String[] names = new String[reader.maxDoc()];
        for (int d = 0; d < names.length; d++) {
            names[d] = stored.document(d, Set.of(Analyzers.NAME_FIELD)).get(Analyzers.NAME_FIELD);
        }
        return names;
    }

    private static long vocabularySize(DirectoryReader reader, String field) throws IOException {
        Terms terms = MultiTerms.getTerms(reader, field);
        if (terms == null) return 0;
        long count = 0;
        TermsEnum it = terms.iterator();
        while (it.next() != null) count++;
        return count;
    }

    private PrintWriter csv(String name) throws IOException {
        return new PrintWriter(Files.newBufferedWriter(results.resolve(name), StandardCharsets.UTF_8));
    }

    private void writeSummaryCsv(String file, Iterable<Run> runs) throws IOException {
        try (PrintWriter csv = csv(file)) {
            csv.println("config,map,p10,r100,r1000,rprec,mrr,ndcg10");
            for (Run r : runs) {
                csv.printf(Locale.ROOT, "%s,%.4f,%.4f,%.4f,%.4f,%.4f,%.4f,%.4f%n", r.label(), Metrics.mean(r.ap()),
                        Metrics.mean(r.p10()), Metrics.mean(r.r100()), Metrics.mean(r.r1000()),
                        Metrics.mean(r.rprec()), Metrics.mean(r.rr()), Metrics.mean(r.ndcg10()));
            }
        }
    }

    private void writeCurveCsv(String file, Iterable<Run> runs) throws IOException {
        try (PrintWriter csv = csv(file)) {
            csv.println("config,recall,precision");
            for (Run r : runs) {
                for (int l = 0; l <= 10; l++) csv.printf(Locale.ROOT, "%s,%.1f,%.4f%n", r.label(), l / 10.0, r.curve()[l]);
            }
        }
    }

    private void writePerQueryCsv(String file, Iterable<Run> runs) throws IOException {
        try (PrintWriter csv = csv(file)) {
            List<Run> list = new ArrayList<>();
            runs.forEach(list::add);
            csv.print("query");
            for (Run r : list) csv.print("," + r.label());
            csv.println();
            for (int i = 0; i < queries.size(); i++) {
                csv.print(queries.get(i).id());
                for (Run r : list) csv.printf(Locale.ROOT, ",%.4f", r.ap()[i]);
                csv.println();
            }
        }
    }

    private static void deleteRecursively(Path dir) throws IOException {
        try (Stream<Path> walk = Files.walk(dir)) {
            for (Path p : walk.sorted(Comparator.reverseOrder()).toList()) Files.deleteIfExists(p);
        }
    }
